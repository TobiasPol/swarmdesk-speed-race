//! SHA-256 (FIPS 180-4). Output: the 32-byte digest.

use super::{random_cases, Case, Target};
use crate::rng::Rng;

pub const TARGET: Target = Target {
    name: "sha256",
    summary: "SHA-256 digest of the input, 32 bytes",
    reference,
    generate,
    out_cap: |_| 32,
};

