fn schedule(block: &[u8]) -> [u32; 64] {
    let mut w = [0u32; 64];
    for i in 0..16 {
        w[i] = u32::from_be_bytes([block[4 * i], block[4 * i + 1], block[4 * i + 2], block[4 * i + 3]]);
    }
    for i in 16..64 {
        let s0 = w[i - 15].rotate_right(7) ^ w[i - 15].rotate_right(18) ^ (w[i - 15] >> 3);
        let s1 = w[i - 2].rotate_right(17) ^ w[i - 2].rotate_right(19) ^ (w[i - 2] >> 10);
        w[i] = w[i - 16].wrapping_add(s0).wrapping_add(w[i - 7]).wrapping_add(s1);
    }
    w
}

fn compress(state: &mut [u32; 8], block: &[u8]) {
    let w = schedule(block);
    let mut v = *state;
    for i in 0..64 {
        let s1 = v[4].rotate_right(6) ^ v[4].rotate_right(11) ^ v[4].rotate_right(25);
        let ch = (v[4] & v[5]) ^ (!v[4] & v[6]);
        let t1 = v[7].wrapping_add(s1).wrapping_add(ch).wrapping_add(K[i]).wrapping_add(w[i]);
        let s0 = v[0].rotate_right(2) ^ v[0].rotate_right(13) ^ v[0].rotate_right(22);
        let maj = (v[0] & v[1]) ^ (v[0] & v[2]) ^ (v[1] & v[2]);
        let t2 = s0.wrapping_add(maj);
        v = [t1.wrapping_add(t2), v[0], v[1], v[2], v[3].wrapping_add(t1), v[4], v[5], v[6]];
    }
    for i in 0..8 {
        state[i] = state[i].wrapping_add(v[i]);
    }
}

fn finish(state: &mut [u32; 8], rest: &[u8], total: usize) {
    let mut tail = [0u8; 128];
    let mut i = 0;
    while i < rest.len() {
        tail[i] = rest[i];
        i += 1;
    }
    tail[rest.len()] = 0x80;
    let size = if rest.len() < 56 { 64 } else { 128 };
    let bits = (total as u64 * 8).to_be_bytes();
    let mut k = 0;
    while k < 8 {
        tail[size - 8 + k] = bits[k];
        k += 1;
    }
    compress(state, &tail[..64]);
    if size == 128 {
        compress(state, &tail[64..]);
    }
}

pub fn solve(input: &[u8], output: &mut [u8]) -> usize {
    let mut state = H0;
    let full = input.len() / 64 * 64;
    let mut pos = 0;
    while pos < full {
        compress(&mut state, &input[pos..pos + 64]);
        pos += 64;
    }
    finish(&mut state, &input[full..], input.len());
    for i in 0..8 {
        let bytes = state[i].to_be_bytes();
        output[4 * i] = bytes[0];
        output[4 * i + 1] = bytes[1];
        output[4 * i + 2] = bytes[2];
        output[4 * i + 3] = bytes[3];
    }
    32
}
